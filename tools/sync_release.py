#!/usr/bin/env python3
"""Refresh the checked-in Release data used by Astro at build time."""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/data/release.ts"
API_URL = "https://api.github.com/repos/EasyKiconverter/EasyKiConverter/releases/latest"
REQUIRED_ASSETS = {
    "windows": ("windows-x86_64-installer.exe", "windows-arm64-installer.exe"),
    "linux": ("linux-x86_64.AppImage", "linux-amd64.deb", "linux-aarch64.AppImage"),
    "macos": ("macos-arm64.dmg", "macos-x86_64.dmg"),
}


def fetch_release() -> dict:
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "EasyKiConverter-Website-build"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = Request(API_URL, headers=headers)
    with urlopen(request, timeout=15) as response:
        return json.load(response)


def build_source(release: dict) -> str:
    tag = release.get("tag_name", "")
    if not tag.startswith("v") or not release.get("html_url"):
        raise ValueError("GitHub Release response is missing a stable tag or URL")
    version = tag.removeprefix("v")
    assets = {asset["name"]: asset["browser_download_url"] for asset in release.get("assets", [])}
    selected: dict[str, list[tuple[str, str]]] = {}
    labels = {
        "windows": ("x86_64 installer", "arm64 installer"),
        "linux": ("x86_64 AppImage", "amd64 DEB", "aarch64 AppImage"),
        "macos": ("Apple Silicon DMG", "Intel DMG"),
    }
    for platform, suffixes in REQUIRED_ASSETS.items():
        matches = []
        for suffix, label in zip(suffixes, labels[platform]):
            names = [name for name in assets if name.endswith(suffix)]
            if len(names) != 1:
                raise ValueError(f"expected one Release asset ending with {suffix!r}, found {names}")
            matches.append((label, assets[names[0]]))
        selected[platform] = matches
    checksum = next((url for name, url in assets.items() if name == "SHA256SUMS"), "")
    if not checksum:
        raise ValueError("latest Release is missing SHA256SUMS")

    lines = [
        "// Generated by tools/sync_release.py; keep the fallback file in Git.",
        'export type ReleaseAsset = { label: string; url: string };',
        "",
        "export const latestRelease = {",
        f'  tag: "{tag}",',
        f'  version: "{version}",',
        f'  url: "{release["html_url"]}",',
        f'  publishedAt: "{release.get("published_at", "")}",',
        f'  checksumUrl: "{checksum}",',
        "  assets: {",
    ]
    for platform in ("windows", "linux", "macos"):
        lines.append(f"    {platform}: [")
        for label, url in selected[platform]:
            lines.append(f'      {{ label: "{label}", url: "{url}" }},')
        lines.extend([f"    ] satisfies ReleaseAsset[],", ""])
    lines.extend(["  },", "} as const;", ""])
    return "\n".join(lines)


def main() -> int:
    try:
        source = build_source(fetch_release())
    except (HTTPError, URLError, TimeoutError, OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        message = f"Release sync unavailable: {error}"
        if os.environ.get("RELEASE_SYNC_REQUIRED") == "1":
            print(message, file=sys.stderr)
            return 1
        print(f"Warning: {message}; using checked-in Release data.", file=sys.stderr)
        return 0
    TARGET.write_text(source, encoding="utf-8")
    print(f"Synced {TARGET.relative_to(ROOT)} to {source.splitlines()[4].split(chr(34))[1]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
