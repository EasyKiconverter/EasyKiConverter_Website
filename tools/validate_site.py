#!/usr/bin/env python3
"""Small source and asset checks for the Astro static website."""
from pathlib import Path
import sys
from html.parser import HTMLParser
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
source_pages = [ROOT / "src/pages/index.astro", ROOT / "src/pages/en/index.astro"]
homepage_source = ROOT / "src/components/HomePage.astro"
lab_source_pages = [ROOT / "src/pages/lab/index.astro", ROOT / "src/pages/en/lab/index.astro"]
seo_source = ROOT / "src/components/SeoHead.astro"
conversion_scene_source = ROOT / "src/components/ConversionScene.astro"
output_pages = [
    ROOT / "dist/index.html",
    ROOT / "dist/en/index.html",
    ROOT / "dist/lab/index.html",
    ROOT / "dist/en/lab/index.html",
    ROOT / "dist/formats/index.html",
    ROOT / "dist/en/formats/index.html",
    ROOT / "dist/cases/index.html",
    ROOT / "dist/en/cases/index.html",
]
content_pages = output_pages[4:]
errors = []
accessibility_css = (ROOT / "src/css/accessibility.css").read_text(encoding="utf-8")
home_polish_css = (ROOT / "src/css/home-polish.css").read_text(encoding="utf-8")
app_source = (ROOT / "src/js/app.ts").read_text(encoding="utf-8")
model_source = (ROOT / "src/js/model-viewer.ts").read_text(encoding="utf-8")
release_source = (ROOT / "src/data/release.ts").read_text(encoding="utf-8")
seo_text = seo_source.read_text(encoding="utf-8")
if ":focus-visible" not in accessibility_css:
    errors.append("src/css/accessibility.css: missing visible keyboard focus rule")
if "prefers-reduced-motion" not in (ROOT / "src/css/styles.css").read_text(encoding="utf-8"):
    errors.append("src/css/styles.css: missing reduced-motion rule")
if ".reveal" not in home_polish_css or "opacity: 1" not in home_polish_css:
    errors.append("src/css/home-polish.css: content is not visible without JavaScript")
if "html:not(.js-ready) .mobile-nav" not in home_polish_css:
    errors.append("src/css/home-polish.css: mobile navigation has no no-JavaScript fallback")
if "classList.add('js-ready')" not in app_source:
    errors.append("src/js/app.ts: JavaScript readiness marker is missing")
if "Generated by tools/sync_release.py" not in release_source:
    errors.append("src/data/release.ts: missing build-time Release sync marker")
if "from '../data/release'" not in app_source or "tag: latestRelease.tag" not in app_source:
    errors.append("src/js/app.ts: runtime Release fallback must use src/data/release.ts")
if 'new URL(import.meta.env.BASE_URL, document.baseURI)' not in model_source:
    errors.append("src/js/model-viewer.ts: Lab assets must resolve from Astro BASE_URL")
if 'assets/vendor/' not in model_source or 'assets/model/Easykiconverter_展示模型.step' not in model_source:
    errors.append("src/js/model-viewer.ts: Lab asset URLs are incomplete")
conversion_scene_text = conversion_scene_source.read_text(encoding="utf-8")
homepage_text = homepage_source.read_text(encoding="utf-8")
if 'modelNormals' not in model_source or 'computeVertexNormals' not in model_source:
    errors.append("src/js/model-viewer.ts: GLB normals must be preserved with a STEP fallback computation")
if 'rendering' not in model_source or 'reducedMotion' not in model_source or 'clearTimeout' not in model_source:
    errors.append("src/js/model-viewer.ts: reduced-motion scheduler must stop continuous Lab animation")
for marker in (
    "name=\"description\"",
    "rel=\"canonical\"",
    "property=\"og:title\"",
    "name=\"twitter:card\"",
    "hreflang=\"en\"",
    "hreflang=\"zh-CN\"",
):
    if marker not in seo_text:
        errors.append(f"{seo_source}: missing shared SEO marker {marker}")

if "Xpedition" in homepage_text:
    errors.append(f"{homepage_source}: stable homepage must not claim Xpedition")
has_product_journey = (
    "ConversionScene" in homepage_text
    and "data-story-rail" in homepage_text
    and "data-story-stage" in homepage_text
    and "data-product-stage" in conversion_scene_text
    and "data-conversion-canvas" in conversion_scene_text
)
if not has_product_journey:
    errors.append(f"{homepage_source}: missing interactive product or model stage")
if "SeoHead" not in homepage_text:
    errors.append(f"{homepage_source}: missing shared SeoHead component")
if "application/ld+json" not in homepage_text:
    errors.append(f"{homepage_source}: missing SoftwareApplication structured data")
has_accessible_stage_fallback = (
    "ConversionScene" in homepage_text
    and "<img" in conversion_scene_text
    and "aria-label" in conversion_scene_text
)
if not has_accessible_stage_fallback or "SiteHeader" not in homepage_text:
    errors.append(f"{homepage_source}: missing accessible interaction fallback or mobile navigation")
for marker in ("download-links", "Windows", "Linux", "macOS", "SHA256"):
    if marker not in homepage_text:
        errors.append(f"{homepage_source}: missing download marker {marker}")

for page in source_pages:
    text = page.read_text(encoding="utf-8")
    expected_language = "en" if page.parent.name == "en" else "zh"
    if f'<HomePage lang="{expected_language}"' not in text:
        errors.append(f"{page}: route must render the shared homepage in {expected_language}")

for page in lab_source_pages:
    text = page.read_text(encoding="utf-8")
    for marker in ("GLB", "STEP/WASM", "lab-warning"):
        if marker not in text:
            errors.append(f"{page}: missing current Lab asset guidance marker {marker}")


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.ids: set[str] = set()
        self.duplicate_ids: set[str] = set()
        self.tags: set[str] = set()
        self.title_count = 0
        self.fragments: list[str] = []
        self.resources: list[tuple[str, str]] = []
        self.aria_labels: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.tags.add(tag)
        if tag.lower() == "title":
            self.title_count += 1
        values = dict(attrs)
        element_id = values.get("id")
        if element_id:
            if element_id in self.ids:
                self.duplicate_ids.add(element_id)
            self.ids.add(element_id)
        label = values.get("aria-labelledby")
        if label:
            self.aria_labels.extend(label.split())
        for attribute in ("href", "src"):
            value = values.get(attribute)
            if value:
                if value.startswith("#"):
                    self.fragments.append(value[1:])
                else:
                    self.resources.append((attribute, value))


if not all(page.exists() for page in output_pages):
    errors.append("dist: missing built HTML; run `pnpm run build` before site validation")
else:
    for page in output_pages:
        parser = PageParser()
        page_text = page.read_text(encoding="utf-8")
        parser.feed(page_text)
        if parser.duplicate_ids:
            errors.append(f"{page}: duplicate HTML id(s): {', '.join(sorted(parser.duplicate_ids))}")
        if parser.title_count != 1:
            errors.append(f"{page}: expected exactly one HTML title, found {parser.title_count}")
        if "main" not in parser.tags or "footer" not in parser.tags or not parser.aria_labels:
            errors.append(f"{page}: missing semantic landmarks or labelled sections")
        for marker in (
            'rel="canonical"',
            'hreflang="zh-CN"',
            'hreflang="en"',
            'property="og:title"',
            'name="twitter:card"',
        ):
            if marker not in page_text:
                errors.append(f"{page}: missing SEO marker {marker}")
        for route in ("formats", "cases", "lab"):
            if route not in page_text:
                errors.append(f"{page}: missing content navigation route {route}")
        if page in content_pages:
            for marker in ('class="content-page-skip"', 'aria-current="page"'):
                if marker not in page_text:
                    errors.append(f"{page}: missing content-page accessibility marker {marker}")
        for fragment in parser.fragments:
            if fragment and fragment not in parser.ids:
                errors.append(f"{page}: missing fragment target #{fragment}")
        for attribute, value in parser.resources:
            parsed = urlparse(value)
            if parsed.scheme or value.startswith("data:"):
                continue
            target = (ROOT / "dist" / parsed.path.lstrip("/")).resolve() if value.startswith("/") else (page.parent / parsed.path).resolve()
            if not target.exists():
                errors.append(f"{page}: missing {attribute} target {value}")

for required in ("assets/model/README.md", "assets/model/README_zh.md", "assets/model/Easykiconverter_展示模型.step", "assets/model/Easykiconverter_展示模型.glb", "assets/model/Easykiconverter_展示模型-mobile.glb", "assets/vendor/occt-import-js.js", "assets/vendor/occt-import-js.wasm"):
    if not (ROOT / "public" / required).exists():
        errors.append(f"missing required file: {required}")
for required in ("assets/showcase/easykiconverter-main-public.webp", "assets/showcase/easykiconverter-export.webp"):
    if not (ROOT / "public" / required).is_file():
        errors.append(f"missing required public screenshot: {required}")
if (ROOT / "dist" / "assets/showcase/easykiconverter-main.webp").exists():
    errors.append("dist: unsanitized local-path screenshot must not be published")
for required in ("src/pages/robots.txt.ts", "src/pages/sitemap.xml.ts"):
    if not (ROOT / required).exists():
        errors.append(f"missing generated SEO endpoint: {required}")
for source_asset in ("assets/showcase/easykiconverter-main.png", "assets/showcase/easykiconverter-export.png"):
    if (ROOT / "dist" / source_asset).exists():
        errors.append(f"dist: source screenshot must not be published: {source_asset}")
for required in ("src/js/app.ts", "src/js/model-viewer.ts", "src/js/step-worker.ts"):
    if not (ROOT / required).exists():
        errors.append(f"missing required source: {required}")

if errors:
    print("\n".join(errors), file=sys.stderr)
    sys.exit(1)
print(f"validated {len(output_pages)} built pages and required assets")
